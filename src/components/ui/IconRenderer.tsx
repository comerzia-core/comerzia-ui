interface Props {
    iconName?: string;
    className?: string;
}

export const IconRenderer = ({ iconName, className = "" }: Props) => {
    if (!iconName) return null;
    
    // Busca el icono, si no existe usa el default
    const icon = iconMap[iconName.toLowerCase()] || iconMap['default'];
    
    return <span className={className}>{icon}</span>;
};